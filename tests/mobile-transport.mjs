import assert from "node:assert/strict";
import { createTransport } from "../outputs/mobile-app/transport.mjs";
const target = {}, call = createTransport(target);
let checks = 0;
assert.equal(target.__qyDrain(), "[]"); checks++;
const first = call("uuid"), second = call("readAsset", { id: "sample" });
const batch = JSON.parse(target.__qyDrain());
assert.equal(batch.length, 2); assert.equal(target.__qyDrain(), "[]"); checks++;
assert.equal(target.__qyReply({ id: batch[1].id, value: "file" }), "ok");
assert.equal(target.__qyReply({ id: batch[0].id, value: "id" }), "ok");
assert.equal(await first, "id"); assert.equal(await second, "file"); checks++;
const failure = call("publish"), [message] = JSON.parse(target.__qyDrain());
const rejected = assert.rejects(failure, /iCloud unavailable/);
assert.equal(target.__qyReply({ id: message.id, error: "iCloud unavailable" }), "ok");
await rejected; checks++;
const pending = call("persist", { state: { title: "</script><script>example</script>" } });
const disconnected = assert.rejects(pending, /connection lost/);
assert.equal(target.__qyTransportFailed("connection lost"), "ok");
await disconnected;
await assert.rejects(call("persist"), /connection lost/);
assert.equal(target.__qyDrain(), "[]"); checks++;
assert.equal(target.__qyReply({ id: 999, value: undefined }), "ok"); checks++;
console.log(JSON.stringify({ passed: checks, scalarJsonBridge: true, retainedCompletionCallback: false }));
